// استيراد نوع MetadataRoute من Next.js
// يُستخدم لإنشاء ملفات Metadata مثل manifest
import { MetadataRoute } from "next";


// دالة مسؤولة عن إنشاء ملف Web App Manifest
// ملف الـ Manifest يحتوي على معلومات تطبيق الـ PWA
// مثل اسم التطبيق، الأيقونات، الألوان، وطريقة عرضه
export default function manifest(): MetadataRoute.Manifest {
  return {

    // الاسم الكامل للتطبيق
    // قد يظهر عند تثبيت التطبيق أو في معلوماته
    name: "FleetTrack - إدارة الأسطول وتتبع السائقين",

    // الاسم المختصر للتطبيق
    // يُستخدم عندما تكون مساحة العرض صغيرة
    short_name: "FleetTrack",

    // وصف مختصر يوضح وظيفة التطبيق
    description:
      "نظام إلكتروني احترافي لإدارة الأسطول ومتابعة السائقين وتتبع المركبات بشكل حي ومباشر.",

    // الصفحة التي سيتم فتحها عند تشغيل التطبيق
    // بعد تثبيته كتطبيق PWA
    start_url: "/tracking",

    // طريقة عرض التطبيق
    // standalone تجعل التطبيق يظهر بشكل مشابه
    // للتطبيقات العادية بدون شريط المتصفح
    display: "standalone",

    // لون خلفية التطبيق أثناء بدء التحميل
    background_color: "#0C1426",

    // اللون الأساسي للتطبيق
    // قد يظهر في شريط الحالة أو واجهة النظام
    theme_color: "#0C1426",

    // تحديد اتجاه عرض التطبيق
    // portrait يعني الوضع الرأسي
    orientation: "portrait",

    // تحديد اتجاه الكتابة من اليمين إلى اليسار
    // مناسب للغة العربية
    dir: "rtl",

    // تحديد اللغة الأساسية للتطبيق
    lang: "ar",

    // قائمة أيقونات التطبيق
    icons: [

      // الأيقونة الأولى بحجم 192 × 192 بكسل
      {
        // مسار الأيقونة داخل مجلد public
        src: "/icons/icon-192.png",

        // أبعاد الأيقونة
        sizes: "192x192",

        // نوع ملف الأيقونة
        type: "image/png",

        // maskable تسمح للنظام بقص الأيقونة
        // وعرضها بأشكال مختلفة بدون فقدان المحتوى
        purpose: "maskable",
      },

      // الأيقونة الثانية بحجم 512 × 512 بكسل
      {
        // مسار الأيقونة داخل مجلد public
        src: "/icons/icon-512.png",

        // أبعاد الأيقونة
        sizes: "512x512",

        // نوع ملف الأيقونة
        type: "image/png",

        // any تعني أن الأيقونة يمكن استخدامها
        // بالشكل الأصلي بدون قص خاص
        purpose: "any",
      },
    ],
  };
}